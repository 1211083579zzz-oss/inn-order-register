const assert = require('node:assert/strict');
const core = require('../h5/sync-core.js');
const clone = value => JSON.parse(JSON.stringify(value));
const actorA = 'aaaaaaaaaaaaaaaa', actorB = 'bbbbbbbbbbbbbbbb';
const data = { version: 2, companies: [{ id: 'c1', name: '云栖旅居', contact: '李女士', phone: '' }], orders: [{ id: 'o1', companyId: 'c1', customerName: '林晓宁', phone: '13800138000', hotelOrder: '云栖山居', base: '莫干山基地', nights: 2, arrivalDate: '2026-11-10', roomType: '亲子房', guestCount: '2人', mealIncluded: '是', feeDetails: '原费用' }] };
const base = core.capture(core.empty(), core.emptyData(), data, actorA);
const projected = core.project(base).data;
const leftData = clone(projected), rightData = clone(projected);
leftData.orders[0].phone = '13900139000'; rightData.orders[0].base = '安吉基地';
const left = core.capture(base, projected, leftData, actorA), right = core.capture(base, projected, rightData, actorB);
const merged = core.merge(left, right), result = core.project(merged);
assert.equal(result.data.orders[0].phone, '13900139000'); assert.equal(result.data.orders[0].base, '安吉基地');
assert.equal(result.conflicts.length, 0);
assert.deepEqual(core.project(core.merge(right, left)), result);
assert.deepEqual(core.project(core.merge(merged, merged)), result);
const namesA = clone(projected), namesB = clone(projected);
namesA.orders[0].customerName = '甲的修改'; namesB.orders[0].customerName = '乙的修改';
const conflicting = core.merge(core.capture(base, projected, namesA, actorA), core.capture(base, projected, namesB, actorB));
const conflict = core.project(conflicting).conflicts.find(item => item.field === 'customerName');
assert.deepEqual(new Set(conflict.choices.map(item => item.value)), new Set(['甲的修改', '乙的修改']));
const resolved = core.resolve(conflicting, conflict, '甲的修改', actorA);
assert.equal(core.project(resolved).data.orders[0].customerName, '甲的修改'); assert.equal(core.project(resolved).conflicts.length, 0);
assert.equal(core.project(core.merge(resolved, conflicting)).conflicts.length, 0);
const removed = clone(projected); removed.orders = [];
const afterDelete = core.merge(core.capture(base, projected, removed, actorA), right);
assert.equal(core.project(afterDelete).data.orders.length, 0);
const companyRemoved = clone(projected); companyRemoved.companies = []; companyRemoved.orders[0].companyId = '';
const newGuest = clone(projected); newGuest.orders.push({ ...projected.orders[0], id: 'offline-new' });
const deleteCompanyState = core.merge(core.capture(base, projected, companyRemoved, actorA), core.capture(base, projected, newGuest, actorB));
assert.equal(core.project(deleteCompanyState).data.orders.length, 2);
assert.ok(core.project(deleteCompanyState).data.orders.every(order => order.companyId === ''));
const duplicateData = clone(data); duplicateData.companies[0].id = 'c2'; duplicateData.orders[0].id = 'o2'; duplicateData.orders[0].companyId = 'c2';
const duplicate = core.merge(base, core.capture(core.empty(), core.emptyData(), duplicateData, actorB));
assert.equal(core.project(duplicate).data.companies.length, 1); assert.equal(core.project(duplicate).data.orders.length, 2);
assert.ok(core.project(duplicate).data.orders.every(order => order.companyId === 'c1'));
const duplicateProjection = core.project(duplicate).data, removeBoth = clone(duplicateProjection);
removeBoth.companies = []; removeBoth.orders.forEach(order => { order.companyId = ''; });
assert.equal(core.project(core.capture(duplicate, duplicateProjection, removeBoth, actorA)).data.companies.length, 0);
assert.throws(() => core.validate({ ...base, clock: { bad: 1 } }));

(async () => {
  const code = core.code(), keys = await core.derive(code), encrypted = await core.encrypt(conflicting, keys);
  assert.ok(!JSON.stringify(encrypted).includes('林晓宁'));
  assert.deepEqual(await core.decrypt(encrypted, keys), conflicting);
  assert.notEqual(keys.room, keys.token); assert.ok(!code.includes(keys.token));
  await assert.rejects(core.decrypt(encrypted, await core.derive(core.code())));
  const tampered = { ...encrypted, ciphertext: (encrypted.ciphertext[0] === 'A' ? 'B' : 'A') + encrypted.ciphertext.slice(1) };
  await assert.rejects(core.decrypt(tampered, keys));
  console.log('PASS encrypted AES-GCM roundtrip/tamper/wrong-key; field merge; same-field conflict retained/resolved; offline deletions; company membership; duplicate names; idempotent and commutative merge');
})().catch(error => { console.error(error); process.exitCode = 1; });
