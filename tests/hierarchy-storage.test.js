const assert = require('node:assert/strict');
const { createStore, DATA_KEY } = require('../h5/storage.js');
const values = new Map();
let rejectWrites = false;
const storage = { getItem:key=>values.get(key) ?? null, setItem(key,value) { if(rejectWrites) throw new Error('QuotaExceededError'); values.set(key,value); } };
const store = createStore(storage);
const alpha = store.saveCompany({name:'甲旅居公司'}), beta = store.saveCompany({name:'乙旅居公司'});
const guest = store.saveOrder({id:'guest-1',companyId:alpha.id,customerName:'测试住客'},alpha.id);
assert.equal(guest.companyId,alpha.id);
const original = values.get(DATA_KEY);
assert.throws(()=>store.saveOrder({id:'guest-2',customerName:'无所属公司'},''),/旅居公司/);
assert.throws(()=>store.saveOrder({id:'guest-2',companyId:beta.id},alpha.id),/旅居公司/);
assert.throws(()=>store.saveOrder({...guest,companyId:beta.id},beta.id),/所属/);
assert.equal(values.get(DATA_KEY),original);
store.saveOrder({...guest,feeDetails:'更新费用'},alpha.id);
assert.equal(store.read().orders.length,1);
assert.equal(store.read().orders[0].feeDetails,'更新费用');
store.saveOrders([...store.read().orders,{id:'old-guest',companyId:'',customerName:'历史住客'}]);
store.saveOrder({...store.read().orders.find(o=>o.id==='old-guest'),companyId:beta.id},beta.id);
assert.equal(store.read().orders.find(o=>o.id==='old-guest').companyId,beta.id);
const beforeFailure = values.get(DATA_KEY);
rejectWrites=true;
assert.throws(()=>store.saveOrder({id:'failed-save',companyId:alpha.id},alpha.id),/Quota/);
assert.equal(values.get(DATA_KEY),beforeFailure);
console.log('PASS company-required registration; wrong-parent and cross-company rejection without mutation; in-company edit; legacy assignment; atomic write failure');
