const assert = require('node:assert/strict');
const { createStore, DATA_KEY, LEGACY_KEY } = require('../h5/storage.js');
const values = new Map();
let rejectWrites = false;
const storage = { getItem: key => values.get(key) ?? null, setItem(key, value) { if (rejectWrites) throw new Error('QuotaExceededError'); values.set(key, value); } };
const legacy = [{ id: 'old-1', hotelName: '青禾民宿', orderTitle: '微信预订', customerName: '旧客人', companyName: '原有旅居', adults: 2, children: 1 }, { id: 'old-2', hotelOrder: '旧登记', customerName: '未归属客人' }];
values.set(LEGACY_KEY, JSON.stringify(legacy));
const store = createStore(storage);
const migrated = store.read();
assert.equal(migrated.orders.length, 2);
assert.equal(migrated.companies[0].name, '原有旅居');
assert.equal(migrated.orders[0].companyId, migrated.companies[0].id);
assert.equal(migrated.orders[1].companyId, '');
assert.equal(migrated.orders[0].guestCount, '2大1小');
assert.equal(values.get(LEGACY_KEY), JSON.stringify(legacy));
assert.deepEqual(createStore(storage).read(), migrated);
const alpha = store.saveCompany({ name: '云栖旅居', category: '长期合作', contact: '测试联系人' });
const beta = store.saveCompany({ name: '山海旅居', category: '渠道公司' });
assert.throws(() => store.saveCompany({ name: '  云栖旅居  ' }), /已经登记/);
store.saveOrders([...store.read().orders, { id: 'new-stay', companyId: alpha.id, customerName: '新客人' }]);
const renamed = store.saveCompany({ ...alpha, name: '云栖旅居更新', category: '核心合作' });
assert.equal(renamed.id, alpha.id);
assert.equal(store.read().orders.find(order => order.id === 'new-stay').companyId, alpha.id);
let before = values.get(DATA_KEY);
rejectWrites = true;
assert.throws(() => store.saveCompany({ name: '存储失败公司' }), /Quota/);
assert.equal(values.get(DATA_KEY), before);
assert.throws(() => store.removeCompany(alpha.id), /Quota/);
assert.equal(values.get(DATA_KEY), before);
rejectWrites = false;
const backup = store.backup();
assert.equal(backup.version, 2);
assert.equal(backup.companies.length, 3);
assert.equal(backup.orders.length, 3);
const sameName = { ...renamed, id: 'foreign-company-id' };
store.mergeBackup(store.parseBackup({ app: 'wechat-inn-orders', version: 2, companies: [sameName], orders: [{ id: 'imported-stay', companyId: sameName.id }] }));
assert.equal(store.read().companies.length, 3);
assert.equal(store.read().orders.find(order => order.id === 'imported-stay').companyId, alpha.id);
store.mergeBackup(store.parseBackup({ app: 'wechat-inn-orders', version: 1, orders: [{ id: 'new-stay', customerName: '旧备份更新' }] }));
assert.equal(store.read().orders.find(order => order.id === 'new-stay').companyId, alpha.id);
store.mergeBackup(store.parseBackup({ app: 'wechat-inn-orders', version: 2, companies: [], orders: [{ id: 'missing-company-stay', companyId: 'unknown' }] }));
assert.equal(store.read().orders.find(order => order.id === 'missing-company-stay').companyId, '');
assert.throws(() => store.parseBackup({ app: 'wechat-inn-orders', version: 2, companies: 'wrong', orders: [] }), /格式/);
assert.throws(() => store.parseBackup({ app: 'wechat-inn-orders', version: 9, companies: [], orders: [] }), /格式/);
assert.throws(() => store.parseBackup({ app: 'wechat-inn-orders', version: 2, companies: [{ id: 'x', name: '公司' }, { id: 'x', name: '重复公司' }], orders: [] }), /重复/);
before = store.read();
store.removeCompany(alpha.id);
assert.equal(store.read().orders.length, before.orders.length);
assert.equal(store.read().orders.find(order => order.id === 'new-stay').companyId, '');
assert.ok(store.read().companies.some(company => company.id === beta.id));
values.set(DATA_KEY, 'malformed');
assert.throws(() => store.read(), /无法读取/);
assert.equal(values.get(DATA_KEY), 'malformed');
console.log('PASS company migration, classification, unique names, identity-preserving rename, guest membership, atomic failed writes, full backup, merge remap, v1 compatibility, deletion without guest loss, corrupt data preservation');
